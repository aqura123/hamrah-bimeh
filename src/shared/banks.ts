export function identifyBank(number: string) {
  let best: (typeof IRANIAN_BANKS)[number] | undefined;
  let bestLength = 0;
  for (const bank of IRANIAN_BANKS)
    for (const prefix of bank.bins) {
      if (number.startsWith(prefix) && prefix.length > bestLength) {
        best = bank;
        bestLength = prefix.length;
      }
    }
  return best;
}

export function isValidCardNumber(number: string): boolean {
  if (!/^\d{16}$/.test(number) || /^(\d)\1{15}$/.test(number)) return false;
  let sum = 0;
  for (let i = 0; i < 16; i++) {
    let n = Number(number[i]);
    if (i % 2 === 0) {
      n *= 2;
      if (n > 9) n -= 9;
    }
    sum += n;
  }
  return sum % 10 === 0;
}
